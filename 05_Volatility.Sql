WITH stock_coverage AS (
    SELECT
        SYMBOL,
        COUNT(*) AS RECORDED_DAYS
    FROM STOCK_PRICES
    WHERE DATE >= '2025-01-01'
      AND DATE < '2026-01-01'
    GROUP BY SYMBOL
),
daily_prices AS (
    SELECT
        S.SYMBOL,
        S.DATE,
        S.CLOSE,
        LAG(S.CLOSE) OVER (
            PARTITION BY S.SYMBOL
            ORDER BY S.DATE
        ) AS PREVIOUS_CLOSE
    FROM STOCK_PRICES S
    JOIN stock_coverage C
        ON S.SYMBOL = C.SYMBOL
    WHERE S.DATE >= '2024-12-01'
      AND S.DATE < '2026-01-01'
      AND C.RECORDED_DAYS >= 240
),
daily_returns AS (
    SELECT
        SYMBOL,
        DATE,
        (CLOSE - PREVIOUS_CLOSE)
            / NULLIF(PREVIOUS_CLOSE, 0) * 100
            AS DAILY_RETURN_PERCENT
    FROM daily_prices
    WHERE DATE >= '2025-01-01'
      AND DATE < '2026-01-01'
      AND PREVIOUS_CLOSE IS NOT NULL
)
SELECT
    SYMBOL,
    COUNT(*) AS RETURN_OBSERVATIONS,
    ROUND(AVG(DAILY_RETURN_PERCENT), 4)
        AS AVG_DAILY_RETURN_PERCENT,
    ROUND(STDDEV_POP(DAILY_RETURN_PERCENT), 4)
        AS DAILY_VOLATILITY_PERCENT,
    ROUND(
        STDDEV_POP(DAILY_RETURN_PERCENT) * SQRT(252),
        2
    ) AS ANNUALIZED_VOLATILITY_PERCENT
FROM daily_returns
GROUP BY SYMBOL
ORDER BY ANNUALIZED_VOLATILITY_PERCENT DESC;