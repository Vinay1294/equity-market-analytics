WITH monthly_prices AS (
    SELECT
        SYMBOL,
        YEAR(DATE) AS YEAR,
        MONTH(DATE) AS MONTH,
        AVG(CLOSE) AS AVERAGE_CLOSING_PRICE
    FROM STOCK_PRICES
    WHERE DATE >= '2025-01-01'
      AND DATE < '2026-01-01'
    GROUP BY
        SYMBOL,
        YEAR(DATE),
        MONTH(DATE)
),
monthly_comparison AS (
    SELECT
        SYMBOL,
        YEAR,
        MONTH,
        AVERAGE_CLOSING_PRICE,
        LAG(AVERAGE_CLOSING_PRICE) OVER (
            PARTITION BY SYMBOL
            ORDER BY YEAR, MONTH
        ) AS PREVIOUS_MONTH_AVERAGE
    FROM monthly_prices
)
SELECT
    SYMBOL,
    YEAR,
    MONTH,
    ROUND(AVERAGE_CLOSING_PRICE, 2)
        AS AVERAGE_CLOSING_PRICE,
    ROUND(PREVIOUS_MONTH_AVERAGE, 2)
        AS PREVIOUS_MONTH_AVERAGE,
    ROUND(
        AVERAGE_CLOSING_PRICE - PREVIOUS_MONTH_AVERAGE,
        2
    ) AS PRICE_CHANGE,
    ROUND(
        (AVERAGE_CLOSING_PRICE - PREVIOUS_MONTH_AVERAGE)
        / NULLIF(PREVIOUS_MONTH_AVERAGE, 0) * 100,
        2
    ) AS PRICE_CHANGE_PERCENT
FROM monthly_comparison
ORDER BY SYMBOL, YEAR, MONTH;
