-- COMPARE STOCK PERFORMANCE WITH VOLATILITY.
-- TO CALCULATES THE EACH STOCK'S PRICE CHANGE BETWEEN ITS FIRST AND LAST RECORDED DAILY CLOSING PRICES IN 2025, PLUS ITS ANNULIZED VOLATILITY BASED ON DAILY RETURNS.


WITH daily_prices AS (
    SELECT
        SYMBOL,
        DATE,
        CLOSE,
        LAG(CLOSE) OVER (
            PARTITION BY SYMBOL
            ORDER BY DATE
        ) AS PREVIOUS_CLOSE
    FROM STOCK_PRICES
    WHERE DATE >= '2024-12-01'
      AND DATE < '2026-01-01'
),
daily_returns AS (
    SELECT
        SYMBOL,
        DATE,
        CLOSE,
        PREVIOUS_CLOSE,
        (CLOSE - PREVIOUS_CLOSE)
            / NULLIF(PREVIOUS_CLOSE, 0) * 100
            AS DAILY_RETURN_PERCENT
    FROM daily_prices
),
annual_returns AS (
    SELECT
        SYMBOL,
        FIRST_VALUE(CLOSE) OVER (
            PARTITION BY SYMBOL
            ORDER BY DATE
        ) AS FIRST_CLOSE,
        LAST_VALUE(CLOSE) OVER (
            PARTITION BY SYMBOL
            ORDER BY DATE
            ROWS BETWEEN UNBOUNDED PRECEDING
            AND UNBOUNDED FOLLOWING
        ) AS LAST_CLOSE
    FROM daily_returns
    WHERE DATE >= '2025-01-01'
      AND DATE < '2026-01-01'
),
volatility AS (
    SELECT
        SYMBOL,
        STDDEV_POP(DAILY_RETURN_PERCENT)
            * SQRT(252) AS ANNUALIZED_VOLATILITY
    FROM daily_returns
    WHERE DATE >= '2025-01-01'
      AND DATE < '2026-01-01'
      AND DAILY_RETURN_PERCENT IS NOT NULL
    GROUP BY SYMBOL
)
SELECT
    a.SYMBOL,
    ROUND(MAX(a.FIRST_CLOSE), 2) AS FIRST_CLOSE,
    ROUND(MAX(a.LAST_CLOSE), 2) AS LAST_CLOSE,
    ROUND(
        (MAX(a.LAST_CLOSE) - MAX(a.FIRST_CLOSE))
        / NULLIF(MAX(a.FIRST_CLOSE), 0) * 100,
        2
    ) AS PRICE_CHANGE_PERCENT,
    ROUND(MAX(v.ANNUALIZED_VOLATILITY), 2)
        AS ANNUALIZED_VOLATILITY_PERCENT
FROM annual_returns a
JOIN volatility v
    ON a.SYMBOL = v.SYMBOL
GROUP BY a.SYMBOL
ORDER BY PRICE_CHANGE_PERCENT DESC;

-- LEARN MAXIMUM DRAWDOWN.
-- CALCULATE THE MAXIMUM DRAWDOWN FOR EACH STOCK USING DAILY CLOSING PRICES IN 2025.


WITH running_peaks AS (
    SELECT
        SYMBOL,
        DATE,
        CLOSE,
        MAX(CLOSE) OVER (
            PARTITION BY SYMBOL
            ORDER BY DATE
            ROWS BETWEEN UNBOUNDED PRECEDING
            AND CURRENT ROW
        ) AS RUNNING_PEAK
    FROM STOCK_PRICES
    WHERE DATE >= '2025-01-01'
      AND DATE < '2026-01-01'
),
drawdowns AS (
    SELECT
        SYMBOL,
        DATE,
        CLOSE,
        RUNNING_PEAK,
        (CLOSE - RUNNING_PEAK)
            / NULLIF(RUNNING_PEAK, 0) * 100
            AS DRAWDOWN_PERCENT
    FROM running_peaks
)
SELECT
    SYMBOL,
    ROUND(MIN(DRAWDOWN_PERCENT), 2)
        AS MAXIMUM_DRAWDOWN_PERCENT
FROM drawdowns
GROUP BY SYMBOL
ORDER BY MAXIMUM_DRAWDOWN_PERCENT ASC;

