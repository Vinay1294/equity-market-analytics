-- FIND THE FIRST AND LAST RECORDED CLOSING PRICES FOR EACH STOCK IN 2025.

WITH ranked_prices AS (
    SELECT
        SYMBOL,
        DATE,
        CLOSE,
        ROW_NUMBER() OVER (
            PARTITION BY SYMBOL
            ORDER BY DATE ASC
        ) AS first_rank,
        ROW_NUMBER() OVER (
            PARTITION BY SYMBOL
            ORDER BY DATE DESC
        ) AS last_rank
    FROM STOCK_PRICES
    WHERE DATE >= '2025-01-01'
      AND DATE < '2026-01-01'
)
SELECT
    SYMBOL,
    MAX(CASE WHEN first_rank = 1 THEN DATE END) AS FIRST_RECORD_DATE,
    MAX(CASE WHEN first_rank = 1 THEN CLOSE END) AS FIRST_CLOSING_PRICE,
    MAX(CASE WHEN last_rank = 1 THEN DATE END) AS LAST_RECORD_DATE,
    MAX(CASE WHEN last_rank = 1 THEN CLOSE END) AS LAST_CLOSING_PRICE
FROM ranked_prices
GROUP BY SYMBOL
ORDER BY SYMBOL;

-- CALCULATE PRICE CHANGE AND PERCENTAGE CHANGE.
-- USE THOSE  FIRST AND LAST CLOSING PRICES TO MEASURE HOW MUCH EACH STOCK PRICES CHANGED DURING 2025.


WITH ranked_prices AS (
    SELECT
        SYMBOL,
        DATE,
        CLOSE,
        ROW_NUMBER() OVER (
            PARTITION BY SYMBOL
            ORDER BY DATE ASC
        ) AS first_rank,
        ROW_NUMBER() OVER (
            PARTITION BY SYMBOL
            ORDER BY DATE DESC
        ) AS last_rank
    FROM STOCK_PRICES
    WHERE DATE >= '2025-01-01'
      AND DATE < '2026-01-01'
),
yearly_prices AS (
    SELECT
        SYMBOL,
        MAX(CASE WHEN first_rank = 1 THEN CLOSE END)
            AS FIRST_CLOSING_PRICE,
        MAX(CASE WHEN last_rank = 1 THEN CLOSE END)
            AS LAST_CLOSING_PRICE
    FROM ranked_prices
    GROUP BY SYMBOL
)
SELECT
    SYMBOL,
    FIRST_CLOSING_PRICE,
    LAST_CLOSING_PRICE,
    ROUND(
        LAST_CLOSING_PRICE - FIRST_CLOSING_PRICE, 2
