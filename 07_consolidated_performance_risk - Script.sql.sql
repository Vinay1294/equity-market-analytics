    SELECT
        SYMBOL,
        STDDEV_POP(DAILY_RETURN_PERCENT)
            * SQRT(252) AS ANNUALIZED_VOLATILITY
    FROM daily_returns
    GROUP BY SYMBOL
),

running_peaks AS (
    SELECT
        S.SYMBOL,
        S.DATE,
        S.CLOSE,
        MAX(S.CLOSE) OVER (
            PARTITION BY S.SYMBOL
            ORDER BY S.DATE
            ROWS BETWEEN UNBOUNDED PRECEDING
