-- CALUCLATE ANNUAL PRICE CHANGES ONLY FOR STOCKS WITH AT LEAST 240 RECORDED DAYS IN 2025.


WITH stock_coverage AS (
    SELECT
        SYMBOL,
        COUNT(*) AS RECORDED_DAYS
    FROM STOCK_PRICES
    WHERE DATE >= '2025-01-01'
      AND DATE < '2026-01-01'
    GROUP BY SYMBOL
),
ranked_prices AS (
    SELECT
        S.SYMBOL,
        S.DATE,
        S.CLOSE,
        ROW_NUMBER() OVER (
            PARTITION BY S.SYMBOL
            ORDER BY S.DATE ASC
        ) AS FIRST_RANK,
        ROW_NUMBER() OVER (
            PARTITION BY S.SYMBOL
            ORDER BY S.DATE DESC
        ) AS LAST_RANK
    FROM STOCK_PRICES S
    JOIN stock_coverage C
        ON S.SYMBOL = C.SYMBOL
    WHERE S.DATE >= '2025-01-01'
      AND S.DATE < '2026-01-01'
      AND C.RECORDED_DAYS >= 240
),
annual_prices AS (
    SELECT
        SYMBOL,
        MAX(CASE
            WHEN FIRST_RANK = 1 THEN CLOSE
        END) AS FIRST_CLOSE,
        MAX(CASE
            WHEN LAST_RANK = 1 THEN CLOSE
        END) AS LAST_CLOSE
    FROM ranked_prices
    GROUP BY SYMBOL
)
SELECT
    A.SYMBOL,
    C.RECORDED_DAYS,
    ROUND(A.FIRST_CLOSE, 2) AS FIRST_CLOSE,
    ROUND(A.LAST_CLOSE, 2) AS LAST_CLOSE,
    ROUND(A.LAST_CLOSE - A.FIRST_CLOSE, 2)
        AS PRICE_CHANGE,
    ROUND(
        (A.LAST_CLOSE - A.FIRST_CLOSE)
        / NULLIF(A.FIRST_CLOSE, 0) * 100,
        2
    ) AS PRICE_CHANGE_PERCENT
FROM annual_prices A
JOIN stock_coverage C
    ON A.SYMBOL = C.SYMBOL
ORDER BY PRICE_CHANGE_PERCENT DESC;

