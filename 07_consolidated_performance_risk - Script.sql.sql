SELECT
    A.SYMBOL,
    C.RECORDED_DAYS,
    ROUND(A.FIRST_CLOSE, 2) AS FIRST_CLOSE,
    ROUND(A.LAST_CLOSE, 2) AS LAST_CLOSE,
    ROUND(
        (A.LAST_CLOSE - A.FIRST_CLOSE)
        / NULLIF(A.FIRST_CLOSE, 0) * 100,
        2
    ) AS PRICE_CHANGE_PERCENT,
    ROUND(V.ANNUALIZED_VOLATILITY, 2)
        AS ANNUALIZED_VOLATILITY_PERCENT,
    ROUND(D.MAX_DRAWDOWN_PERCENT, 2)
        AS MAX_DRAWDOWN_PERCENT
FROM annual_performance A
JOIN stock_coverage C
    ON A.SYMBOL = C.SYMBOL
JOIN volatility V
    ON A.SYMBOL = V.SYMBOL
JOIN maximum_drawdown D
    ON A.SYMBOL = D.SYMBOL
ORDER BY PRICE_CHANGE_PERCENT DESC;











