annual_ranked AS (
    SELECT
        S.SYMBOL,
        S.DATE,
        S.CLOSE,
        ROW_NUMBER() OVER (
            PARTITION BY S.SYMBOL
            ORDER BY S.DATE ASC
        ) AS FIRST_RANK,
        ROW_NUMBER() OVER (
            PARTITION BY S.SYMBOL
            ORDER BY S.DATE DESC
        ) AS LAST_RANK
    FROM STOCK_PRICES S
    JOIN stock_coverage C
        ON S.SYMBOL = C.SYMBOL
    WHERE S.DATE >= '2025-01-01'
      AND S.DATE < '2026-01-01'
),

annual_performance AS (
    SELECT
        SYMBOL,
        MAX(CASE
            WHEN FIRST_RANK = 1 THEN CLOSE
        END) AS FIRST_CLOSE,
        MAX(CASE
            WHEN LAST_RANK = 1 THEN CLOSE
        END) AS LAST_CLOSE
    FROM annual_ranked
    GROUP BY SYMBOL
),

daily_prices AS (
    SELECT
        S.SYMBOL,
        S.DATE,
