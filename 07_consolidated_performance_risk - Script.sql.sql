        (LAST_CLOSING_PRICE - FIRST_CLOSING_PRICE)
        / NULLIF(FIRST_CLOSING_PRICE, 0) * 100, 2
    ) AS PRICE_CHANGE_PERCENT
FROM yearly_prices
